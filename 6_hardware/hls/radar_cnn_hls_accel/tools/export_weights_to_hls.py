#!/usr/bin/env python3
"""Export the selected folded RadarDSCNN2D weights to a Vitis HLS header.

The exported graph is:
  stem Conv+BN, four depthwise/pointwise Conv+BN blocks, global average pool,
  and a 1x1 Conv classifier.

It folds each Conv2d+BatchNorm2d pair into a single Conv2d weight/bias:
  W_fold = W * gamma / sqrt(var + eps)
  B_fold = beta - gamma * mean / sqrt(var + eps)

Run from project root after setting PYTHONPATH:
  export PYTHONPATH=$PWD/src
  python 6_hardware/hls/radar_cnn_hls_accel/tools/export_weights_to_hls.py \
    --checkpoint outputs/final_model/radar_dscnn2d_topk3_capped8_best.pth \
    --output 6_hardware/hls/radar_cnn_hls_accel/v1_frame_buffered/weights.h
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import numpy as np
import torch

from radar2dcnn.model import RadarDSCNN2D, load_checkpoint


def fold_conv_bn(conv: torch.nn.Conv2d, bn: torch.nn.BatchNorm2d):
    w = conv.weight.detach().cpu().numpy().astype(np.float64)
    if conv.bias is None:
        b = np.zeros(w.shape[0], dtype=np.float64)
    else:
        b = conv.bias.detach().cpu().numpy().astype(np.float64)

    gamma = bn.weight.detach().cpu().numpy().astype(np.float64)
    beta = bn.bias.detach().cpu().numpy().astype(np.float64)
    mean = bn.running_mean.detach().cpu().numpy().astype(np.float64)
    var = bn.running_var.detach().cpu().numpy().astype(np.float64)
    eps = float(bn.eps)

    scale = gamma / np.sqrt(var + eps)
    w_fold = w * scale.reshape(-1, 1, 1, 1)
    b_fold = beta + (b - mean) * scale
    return w_fold.astype(np.float32), b_fold.astype(np.float32)


def fmt_float(x: float) -> str:
    # Fixed decimal scientific notation that HLS accepts.
    return f"{float(x):.8e}"


def c_array(name: str, arr: np.ndarray, ctype: str = "data_t") -> str:
    def rec(a):
        if a.ndim == 0:
            return fmt_float(float(a))
        return "{" + ", ".join(rec(x) for x in a) + "}"

    dims = "".join(f"[{d}]" for d in arr.shape)
    return f"static const {ctype} {name}{dims} = {rec(arr)};\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--checkpoint", required=True)
    ap.add_argument("--output", default="v1_frame_buffered/weights.h")
    args = ap.parse_args()

    model = load_checkpoint(args.checkpoint, map_location="cpu")
    model.eval()
    if not isinstance(model, RadarDSCNN2D):
        raise TypeError(
            "The current HLS accelerator implements RadarDSCNN2D; "
            f"checkpoint loaded {type(model).__name__}"
        )

    arrays: dict[str, np.ndarray] = {}
    arrays["W_STEM"], arrays["B_STEM"] = fold_conv_bn(
        model.features[0], model.features[1]
    )
    for block_number, feature_index in enumerate((3, 4, 5, 6), start=1):
        block = model.features[feature_index].block
        arrays[f"W_DW{block_number}"], arrays[f"B_DW{block_number}"] = (
            fold_conv_bn(block[0], block[1])
        )
        pointwise_weight, pointwise_bias = fold_conv_bn(block[3], block[4])
        arrays[f"W_PW{block_number}"] = pointwise_weight[:, :, 0, 0]
        arrays[f"B_PW{block_number}"] = pointwise_bias

    arrays["W_CLS"] = (
        model.classifier.weight.detach().cpu().numpy().astype(np.float32)[:, :, 0, 0]
    )
    arrays["B_CLS"] = model.classifier.bias.detach().cpu().numpy().astype(np.float32)

    expected_shapes = {
        "W_STEM": (16, 1, 3, 3), "B_STEM": (16,),
        "W_DW1": (16, 1, 3, 3), "B_DW1": (16,),
        "W_PW1": (32, 16), "B_PW1": (32,),
        "W_DW2": (32, 1, 3, 3), "B_DW2": (32,),
        "W_PW2": (64, 32), "B_PW2": (64,),
        "W_DW3": (64, 1, 3, 3), "B_DW3": (64,),
        "W_PW3": (96, 64), "B_PW3": (96,),
        "W_DW4": (96, 1, 3, 3), "B_DW4": (96,),
        "W_PW4": (128, 96), "B_PW4": (128,),
        "W_CLS": (4, 128), "B_CLS": (4,),
    }
    actual_shapes = {name: value.shape for name, value in arrays.items()}
    if actual_shapes != expected_shapes:
        raise ValueError(
            "Checkpoint does not match the fixed HLS architecture: "
            f"expected {expected_shapes}, got {actual_shapes}"
        )

    checkpoint_path = Path(args.checkpoint)
    checkpoint_sha256 = hashlib.sha256(checkpoint_path.read_bytes()).hexdigest()

    out = []
    out.append('#ifndef RADAR_CNN_WEIGHTS_H\n')
    out.append('#define RADAR_CNN_WEIGHTS_H\n\n')
    out.append('#include "radar_cnn_hls.h"\n\n')
    out.append('// Auto-generated by tools/export_weights_to_hls.py\n')
    out.append(f'// Source checkpoint: {checkpoint_path}\n')
    out.append(f'// Source SHA-256: {checkpoint_sha256}\n')
    out.append('// Conv+BN layers are folded for inference.\n')
    out.append('// Depthwise weights retain PyTorch shape [C][1][3][3].\n\n')
    for name, value in arrays.items():
        out.append(c_array(name, value))
    out.append('\n#endif // RADAR_CNN_WEIGHTS_H\n')

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("".join(out), encoding="utf-8")

    print("Exported HLS weights:", out_path)
    for name, value in arrays.items():
        print(name, value.shape)


if __name__ == "__main__":
    main()
