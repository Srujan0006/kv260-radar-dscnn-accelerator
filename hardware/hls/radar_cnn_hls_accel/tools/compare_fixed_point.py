#!/usr/bin/env python3
"""Prepare and compare fixed-point HLS validation samples against PyTorch.

This script has two jobs:
1. Export a small set of real spectrogram samples plus PyTorch reference logits.
2. Compare Vitis HLS C-simulation output against those references.

It does not require Vitis HLS for the preparation step. The comparison step
expects a text output generated by ``tb_real_samples.cpp``.
"""

from __future__ import annotations

import argparse
import csv
import json
import random
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

import numpy as np
import torch

ACCEL_ROOT = Path(__file__).resolve().parents[1]
PROJECT_ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from radar2dcnn.labels import CLASS_NAMES
from radar2dcnn.model import load_checkpoint


@dataclass
class SampleRef:
    cache_index: int
    label: int
    sample_id: str
    logits: np.ndarray
    prediction: int
    image: np.ndarray


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "command",
        nargs="?",
        choices=["prepare", "compare"],
        default=None,
        help="prepare reference samples or compare captured HLS C-simulation output",
    )
    parser.add_argument(
        "--checkpoint",
        default=str(
            PROJECT_ROOT
            / "outputs/final_model/radar_dscnn2d_topk3_capped8_best.pth"
        ),
    )
    parser.add_argument(
        "--cache",
        "--data",
        dest="cache",
        default=str(
            PROJECT_ROOT
            / "outputs/recordwise_topk3_stride32/test/spectrogram_cache.npz"
        ),
    )
    parser.add_argument(
        "--output-dir",
        default=str(ACCEL_ROOT / "reports" / "fixed_point_validation"),
    )
    parser.add_argument(
        "--sample-indices",
        type=int,
        nargs="*",
        default=None,
        help="Explicit cache indices to export. Overrides balanced sampling.",
    )
    parser.add_argument(
        "--samples-per-class",
        type=int,
        default=2,
        help="Number of samples to export per class when sample-indices is omitted.",
    )
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument(
        "--hls-output",
        default=None,
        help="Path to csim/stdout text generated by tb_real_samples.cpp.",
    )
    parser.add_argument(
        "--reference",
        default=None,
        help="Prepared pytorch_reference.json; used by the compare command",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Comparison report JSON path (default: prediction_match_report.json)",
    )
    parser.add_argument(
        "--atol",
        type=float,
        default=0.10,
        help="Absolute logit tolerance for fixed-point comparison.",
    )
    parser.add_argument(
        "--prediction-threshold",
        type=float,
        default=0.95,
        help="Required prediction match ratio for a passing report.",
    )
    return parser.parse_args()


def choose_indices(labels: np.ndarray, args: argparse.Namespace) -> list[int]:
    if args.sample_indices:
        return sorted(set(int(i) for i in args.sample_indices))

    rng = random.Random(args.seed)
    chosen: list[int] = []
    for class_id in range(len(CLASS_NAMES)):
        candidates = np.flatnonzero(labels == class_id).tolist()
        if not candidates:
            continue
        rng.shuffle(candidates)
        chosen.extend(sorted(candidates[: args.samples_per_class]))
    return sorted(set(chosen))


def load_sample_refs(args: argparse.Namespace) -> list[SampleRef]:
    with np.load(args.cache, allow_pickle=False) as data:
        images = np.asarray(data["images"], dtype=np.float32)
        labels = np.asarray(data["y"], dtype=np.int64)
        if "sample_ids" in data.files:
            sample_ids = [str(x) for x in data["sample_ids"]]
        else:
            sample_ids = [f"sample_{i}" for i in range(len(images))]

    indices = choose_indices(labels, args)
    if not indices:
        raise SystemExit("No samples selected for fixed-point validation.")
    bad = [i for i in indices if i < 0 or i >= len(images)]
    if bad:
        raise IndexError(f"Selected sample indices are out of range: {bad}")

    model = load_checkpoint(args.checkpoint, map_location="cpu")
    refs: list[SampleRef] = []
    with torch.no_grad():
        for idx in indices:
            image = images[idx].reshape(100, 100)
            logits = model(torch.from_numpy(image[None, None])).numpy()[0].astype(np.float32)
            refs.append(
                SampleRef(
                    cache_index=idx,
                    label=int(labels[idx]),
                    sample_id=sample_ids[idx],
                    logits=logits,
                    prediction=int(np.argmax(logits)),
                    image=image,
                )
            )
    return refs


def write_input_samples(path: Path, refs: Iterable[SampleRef]) -> None:
    refs = list(refs)
    with path.open("w", encoding="utf-8") as stream:
        stream.write(f"{len(refs)}\n")
        for ref in refs:
            stream.write(f"{ref.cache_index} {ref.label}\n")
            flat = ref.image.reshape(-1)
            for offset in range(0, flat.size, 16):
                chunk = flat[offset : offset + 16]
                stream.write(" ".join(f"{float(value):.9g}" for value in chunk))
                stream.write("\n")


def write_pytorch_reference(output_dir: Path, refs: Iterable[SampleRef]) -> None:
    refs = list(refs)
    rows = []
    for ref in refs:
        rows.append(
            {
                "cache_index": ref.cache_index,
                "label": ref.label,
                "label_name": CLASS_NAMES[ref.label],
                "sample_id": ref.sample_id,
                "prediction": ref.prediction,
                "prediction_name": CLASS_NAMES[ref.prediction],
                "logits": [float(x) for x in ref.logits],
            }
        )
    (output_dir / "pytorch_reference.json").write_text(
        json.dumps(rows, indent=2), encoding="utf-8"
    )
    with (output_dir / "pytorch_reference.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(
            [
                "cache_index",
                "sample_id",
                "label",
                "label_name",
                "prediction",
                "prediction_name",
                "logit_0",
                "logit_1",
                "logit_2",
                "logit_3",
            ]
        )
        for ref in refs:
            writer.writerow(
                [
                    ref.cache_index,
                    ref.sample_id,
                    ref.label,
                    CLASS_NAMES[ref.label],
                    ref.prediction,
                    CLASS_NAMES[ref.prediction],
                    *[float(x) for x in ref.logits],
                ]
            )


def read_pytorch_reference(path: Path) -> list[SampleRef]:
    rows = json.loads(path.read_text(encoding="utf-8"))
    return [
        SampleRef(
            cache_index=int(row["cache_index"]),
            label=int(row["label"]),
            sample_id=str(row["sample_id"]),
            logits=np.asarray(row["logits"], dtype=np.float32),
            prediction=int(row["prediction"]),
            image=np.empty((0, 0), dtype=np.float32),
        )
        for row in rows
    ]


def parse_hls_output(path: Path) -> dict[int, dict[str, object]]:
    results: dict[int, dict[str, object]] = {}
    current_index: int | None = None
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line:
            continue
        parts = line.split()
        if parts[0] == "SAMPLE" and len(parts) >= 4:
            current_index = int(parts[2])
            results[current_index] = {
                "sample_id": f"cache_index_{current_index}",
                "label": int(parts[3]),
                "logits": [None, None, None, None],
            }
        elif parts[0] == "LOGIT" and len(parts) == 3 and current_index is not None:
            logits = results[current_index]["logits"]
            assert isinstance(logits, list)
            logits[int(parts[1])] = float(parts[2])
        elif parts[0] == "PRED" and len(parts) == 2 and current_index is not None:
            results[current_index]["prediction"] = int(parts[1])
    parsed: dict[int, dict[str, object]] = {}
    for index, item in results.items():
        logits = item["logits"]
        if any(value is None for value in logits):
            raise RuntimeError(f"Incomplete logits for sample index {index} in {path}")
        parsed[index] = {
            "sample_id": item["sample_id"],
            "label": item["label"],
            "prediction": int(item.get("prediction", int(np.argmax(logits)))),
            "logits": np.asarray(logits, dtype=np.float32),
        }
    return parsed


def compare_refs(
    refs: Iterable[SampleRef],
    hls_results: dict[int, dict[str, object]],
    output_dir: Path,
    atol: float,
    prediction_threshold: float,
    report_path: Path | None = None,
) -> None:
    refs = list(refs)
    rows = []
    matched_predictions = 0
    max_abs_error = 0.0
    missing = []
    for ref in refs:
        if ref.cache_index not in hls_results:
            missing.append(ref.cache_index)
            continue
        hls = hls_results[ref.cache_index]
        hls_logits = np.asarray(hls["logits"], dtype=np.float32)
        abs_error = np.abs(ref.logits - hls_logits)
        max_abs_error = max(max_abs_error, float(abs_error.max()))
        prediction_match = int(ref.prediction == int(hls["prediction"]))
        matched_predictions += prediction_match
        rows.append(
            {
                "cache_index": ref.cache_index,
                "sample_id": ref.sample_id,
                "label": ref.label,
                "label_name": CLASS_NAMES[ref.label],
                "pytorch_prediction": ref.prediction,
                "pytorch_prediction_name": CLASS_NAMES[ref.prediction],
                "hls_prediction": int(hls["prediction"]),
                "hls_prediction_name": CLASS_NAMES[int(hls["prediction"])],
                "max_abs_error": float(abs_error.max()),
                "prediction_match": bool(prediction_match),
                "pytorch_logits": [float(x) for x in ref.logits],
                "hls_logits": [float(x) for x in hls_logits],
                "abs_error": [float(x) for x in abs_error],
            }
        )

    if missing:
        raise RuntimeError(f"HLS output is missing sample indices: {missing}")

    with (output_dir / "hls_vs_pytorch_logits.csv").open(
        "w", encoding="utf-8", newline=""
    ) as stream:
        writer = csv.writer(stream)
        writer.writerow(
            [
                "cache_index",
                "sample_id",
                "label_name",
                "pytorch_prediction_name",
                "hls_prediction_name",
                "prediction_match",
                "max_abs_error",
                "pytorch_logit_0",
                "pytorch_logit_1",
                "pytorch_logit_2",
                "pytorch_logit_3",
                "hls_logit_0",
                "hls_logit_1",
                "hls_logit_2",
                "hls_logit_3",
            ]
        )
        for row in rows:
            writer.writerow(
                [
                    row["cache_index"],
                    row["sample_id"],
                    row["label_name"],
                    row["pytorch_prediction_name"],
                    row["hls_prediction_name"],
                    row["prediction_match"],
                    row["max_abs_error"],
                    *row["pytorch_logits"],
                    *row["hls_logits"],
                ]
            )

    ratio = matched_predictions / max(len(refs), 1)
    report = {
        "num_samples": len(refs),
        "prediction_match_count": matched_predictions,
        "prediction_match_ratio": ratio,
        "max_abs_error": max_abs_error,
        "logit_tolerance": atol,
        "prediction_threshold": prediction_threshold,
        "status": (
            "passed"
            if ratio >= prediction_threshold and max_abs_error <= atol
            else "failed"
        ),
        "scope": "fixed-point HLS C simulation vs PyTorch reference",
        "samples": rows,
    }
    if report_path is None:
        report_path = output_dir / "prediction_match_report.json"
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(
        json.dumps(report, indent=2), encoding="utf-8"
    )
    print(json.dumps(report, indent=2))
    if report["status"] != "passed":
        raise SystemExit(
            "FAILED: fixed-point HLS output did not meet the configured tolerance."
        )


def main() -> None:
    args = parse_args()
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    command = args.command or ("compare" if args.hls_output else "prepare")

    if command == "compare":
        if not args.hls_output:
            raise SystemExit("compare requires --hls-output")
        reference_path = (
            Path(args.reference)
            if args.reference
            else output_dir / "pytorch_reference.json"
        )
        refs = read_pytorch_reference(reference_path)
        compare_refs(
            refs=refs,
            hls_results=parse_hls_output(Path(args.hls_output)),
            output_dir=output_dir,
            atol=args.atol,
            prediction_threshold=args.prediction_threshold,
            report_path=Path(args.output) if args.output else None,
        )
    else:
        refs = load_sample_refs(args)
        write_input_samples(output_dir / "input_samples.txt", refs)
        write_pytorch_reference(output_dir, refs)
        manifest = {
            "num_samples": len(refs),
            "checkpoint": args.checkpoint,
            "cache": args.cache,
            "next_step": (
                "Run tb_real_samples.cpp in Vitis HLS C simulation, capture stdout "
                "to csim_output.txt, then rerun this script with --hls-output."
            ),
            "expected_outputs": [
                "input_samples.txt",
                "pytorch_reference.json",
                "pytorch_reference.csv",
            ],
        }
        (output_dir / "prepare_manifest.json").write_text(
            json.dumps(manifest, indent=2), encoding="utf-8"
        )
        print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
